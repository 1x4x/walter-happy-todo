using HappyTodo;
using HappyTodo.Components;
using Microsoft.AspNetCore.Authentication;
using Microsoft.AspNetCore.Authentication.Cookies;
using Microsoft.AspNetCore.Components.Authorization;
using System.Security.Claims;
var builder=WebApplication.CreateBuilder(args);
builder.Services.AddRazorComponents().AddInteractiveServerComponents();
builder.Services.AddCascadingAuthenticationState();
builder.Services.AddHttpContextAccessor();
builder.Services.AddAuthentication(CookieAuthenticationDefaults.AuthenticationScheme).AddCookie(o=>{o.LoginPath="/";o.ExpireTimeSpan=TimeSpan.FromDays(365);o.SlidingExpiration=true;o.Cookie.HttpOnly=true;o.Cookie.SameSite=SameSiteMode.Lax;o.Cookie.SecurePolicy=CookieSecurePolicy.SameAsRequest;});
builder.Services.AddAuthorization();
builder.Services.AddSingleton<TodoStore>();
var app=builder.Build();
if(!app.Environment.IsDevelopment())app.UseHsts();
app.UseHttpsRedirection();app.UseStaticFiles();app.UseAuthentication();app.UseAuthorization();app.UseAntiforgery();
app.MapGet("/admin-entry",async (HttpContext ctx,IConfiguration cfg)=>{
 var provided=ctx.Request.Query["walteradmin"].ToString();
 var expected=cfg["Admin:AccessKey"]??"walter";
 if(provided!=expected)return Results.Redirect("/");
 var identity=new ClaimsIdentity(new[]{new Claim(ClaimTypes.Name,"Walter"),new Claim(ClaimTypes.Role,"Admin")},CookieAuthenticationDefaults.AuthenticationScheme);
 await ctx.SignInAsync(CookieAuthenticationDefaults.AuthenticationScheme,new ClaimsPrincipal(identity),new AuthenticationProperties{IsPersistent=true,ExpiresUtc=DateTimeOffset.UtcNow.AddDays(365)});
 return Results.Redirect("/");
});
app.Use(async (ctx,next)=>{if(ctx.Request.Path=="/"&&ctx.Request.Query.ContainsKey("walteradmin")){ctx.Response.Redirect("/admin-entry?walteradmin="+Uri.EscapeDataString(ctx.Request.Query["walteradmin"].ToString()));return;}await next();});
app.MapGet("/logout",async (HttpContext ctx)=>{await ctx.SignOutAsync(CookieAuthenticationDefaults.AuthenticationScheme);return Results.Redirect("/");});
app.MapRazorComponents<App>().AddInteractiveServerRenderMode();
app.Run();
